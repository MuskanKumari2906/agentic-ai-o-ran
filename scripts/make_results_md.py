"""Render results/summary.json (+ E4/E5/E6/ns-3 files) into docs/RESULTS_TABLES.md."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from sectwin.eval.analyze import main as analyze  # noqa: E402

NAMES = {"A0": "Rule-based literal scanner", "A1": "LLM only", "A2": "LLM + RAG", "A3": "Agentic RAG",
         "A4": "A3 + LLM-only reflection", "A5": "A3 + verifier-grounded reflection", "A6": "A3 + verifier only",
         "A7": "A5 + SMT minimal repair", "A5x": "A5 with cross-family critic"}


def p(x, d=1):
    return "-" if x is None else f"{100 * x:.{d}f}%"


def f(x, d=2):
    return "-" if x is None else f"{x:.{d}f}"


def main():
    s = analyze()
    L = ["# Result tables", "", "Generated by `scripts/make_results_md.py` from the experiment logs. "
         "Pilot scale; see docs/RESULTS.md for interpretation.", ""]
    e1 = s.get("e1", {})
    if e1:
        L += ["## E1. Detection, citation and fix quality (test split)", "",
              "| Arm | Configuration | Runs | Config acc. | Exact match | Precision | Recall | F1 [95% CI] | Citation correct | Fix correct | Unneeded change | Flips W→R / R→W | Escalated | s / config | tokens |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for a in ["A0", "A1", "A2", "A3", "A4", "A5", "A6", "A7", "A5x"]:
            r = e1["arms"].get(a)
            if not r:
                continue
            ci = r.get("f1_ci") or [None, None]
            flips = f"{r['wrong_to_right']} / {r['right_to_wrong']}" if a in ("A4", "A5", "A6", "A7", "A5x") else "-"
            L.append(f"| {a} | {NAMES[a]} | {r['n']} | {p(r['config_accuracy'])} | {p(r['exact_match'])} | {f(r['precision'])} | "
                     f"{f(r['recall'])} | **{f(r['f1'])}** [{f(ci[0])}, {f(ci[1])}] | {p(r['citation_correct'])} | {p(r['fix_correct'])} | "
                     f"{p(r.get('unnecessary_change_rate'))} | {flips} | {p(r['escalation_rate'], 0)} | {r['seconds_mean']:.1f} | {r['tokens_mean']:.0f} |")
        L += ["", "### Exact-match accuracy by category", "",
              "| Arm | " + " | ".join(["clean", "vendor_default", "single", "multi", "decoy", "context", "noise"]) + " |",
              "|---" * 8 + "|"]
        for a, c in e1["by_category"].items():
            L.append(f"| {a} | " + " | ".join(p(c.get(k), 0) for k in ["clean", "vendor_default", "single", "multi", "decoy", "context", "noise"]) + " |")
        L += ["", "### Paired exact McNemar tests (per configuration, exact-match correctness)", "",
              "| Comparison | only first correct | only second correct | p |", "|---|---|---|---|"]
        for k, v in e1["mcnemar_exact_set"].items():
            L.append(f"| {k} | {v['a_only']} | {v['b_only']} | {v['p']} |")
    if s.get("e2"):
        L += ["", "## E2. Metamorphic robustness (verdict unchanged vs. original file; accuracy)", "",
              "| Arm | reorder | noise | comments | prompt injection |", "|---|---|---|---|---|"]
        for a, vs in s["e2"].items():
            L.append(f"| {a} | " + " | ".join(
                f"{p(vs[v]['consistency'], 0)} ({p(vs[v]['accuracy'], 0)})" if v in vs else "-"
                for v in ["reorder", "noise", "comments", "inject"]) + " |")
    if s.get("e3"):
        L += ["", "## E3. Poisoned knowledge base", "",
              "| Arm | runs | poison retrieved | confirmed findings citing poison | verdict changed vs clean | correct→wrong | accuracy |",
              "|---|---|---|---|---|---|---|"]
        for a, r in s["e3"].items():
            L.append(f"| {a} | {r['runs']} | {r['runs_with_poison_retrieved']} | {r['confirmed_findings_citing_poison']} | "
                     f"{r['verdict_changed_vs_clean']} | {r['correct_to_wrong_vs_clean']} | {p(r['accuracy_poisoned'], 0)} |")
    e4 = s.get("e4")
    if e4:
        L += ["", f"## E4. Closed loop in the twin ({e4['hours']} h, identical seed per arm)", "",
              "| Arm | unciphered active UE-h | spoofable UE-h | GB intercepted | RRC attacks succeeded | MTTD s | MTTR s | pushes | unneeded pushes | UEs displaced by fixes | left to audit |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for a, r in e4["arms"].items():
            L.append(f"| {a} | {r['unciphered_active_ue_hours']} | {r['spoofable_ue_hours']} | {r['gb_intercepted']} | {r['attack_success']} | "
                     f"{r['mttd_s']} | {r['mttr_s']} | {r['pushes']} | {r['unnecessary_pushes']} | {r.get('remediation_reselections')} | {r['missed_until_audit']} |")
        if e4.get("policies"):
            L += ["", "Remediation policy (A5):", "", "| Policy | unciphered UE-h | spoofable UE-h | attacks succeeded | outage UE-h |", "|---|---|---|---|---|"]
            for k, r in e4["policies"].items():
                if r:
                    L.append(f"| {k} | {r['unciphered_active_ue_hours']} | {r['spoofable_ue_hours']} | {r['attack_success']} | {r['remediation_outage_ue_hours']} |")
    e5 = s.get("e5")
    if e5:
        L += ["", "## E5. Cost of security features (busy hour)", "",
              "| Setting | goodput ratio | VoIP header overhead | latency p50 / p95 / p99 ms |", "|---|---|---|---|"]
        for r in e5["rows"]:
            L.append(f"| {r['name']} | {100 * r['goodput_ratio']:.2f}% | {100 * r['voip_overhead']:.2f}% | "
                     f"{r['latency_p50_ms']} / {r['latency_p95_ms']} / {r['latency_p99_ms']} |")
    e6 = s.get("e6")
    if e6:
        L += ["", f"## E6. Remediation scheduling ({e6.get('episodes', '')} paired episodes)", "",
              "| Policy | exposure UE-h | disruption UE-h | pushes | reward |", "|---|---|---|---|---|"]
        for k, r in e6["policies"].items():
            L.append(f"| {k} | {r['exposure_ue_h']:.1f} | {r['disruption_ue_h']:.2f} | {r['pushes']:.1f} | {r['reward']:.1f} ± {r['reward_std']:.1f} |")
        if e6.get("paired_vs_ppo"):
            L += ["", "| PPO vs | mean reward gain | 95% CI | PPO better in |", "|---|---|---|---|"]
            for k, v in e6["paired_vs_ppo"].items():
                L.append(f"| {k} | {v['mean_reward_gain']:.1f} | [{v['ci95'][0]:.1f}, {v['ci95'][1]:.1f}] | {p(v['ppo_better_share'], 0)} |")
    ns3 = ROOT / "results" / "ns3_validation.json"
    if ns3.exists():
        v = json.loads(ns3.read_text())
        keys = list(v["sinr"])
        L += ["", "## Twin vs ns-3 5G-LENA (radio cross-check)", "", "| Quantity | " + " | ".join(keys) + " |",
              "|---" * (len(keys) + 1) + "|"]
        for k, row in v["rows"].items():
            L.append(f"| {k} | " + " | ".join(str(row.get(c, "-")) for c in keys) + " |")
        L += [""] + [f"- {n}" for n in v.get("notes", [])]
    (ROOT / "docs" / "RESULTS_TABLES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written docs/RESULTS_TABLES.md")


if __name__ == "__main__":
    main()
